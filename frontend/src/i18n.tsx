// Les écrans du cadrage RH ont leur dictionnaire à part (i18nEcrans.ts) : le fichier principal reste lisible.
export const DICTS: Record<Lang, Dict> = { fr: { ...fr, ...ecransFr }, en: { ...en, ...ecransEn }, mg: { ...mg, ...ecransMg } };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string>) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

function detectInitial(): Lang {
  if (typeof window === "undefined") return "fr";
  const saved = localStorage.getItem("lang") as Lang | null;
  if (saved && DICTS[saved]) return saved;
  // **Le français d'abord, quelle que soit la langue du navigateur** (AO 26-015-DO, E-TN-21 :
  // « La solution doit avoir une interface en français »). Un poste réglé en anglais ouvrait la
  // connexion en anglais ; la personne choisit une autre langue d'un clic, et ce choix est retenu.
  return "fr";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectInitial);
  useEffect(() => { localStorage.setItem("lang", lang); document.documentElement.lang = lang; }, [lang]);

  function t(key: string, vars?: Record<string, string>): string {
    const dict = DICTS[lang] || fr;
    let s = dict[key] ?? fr[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), v);
      }
    }
    return s;
  }

  return <Ctx.Provider value={{ lang, setLang: setLangState, t }}>{children}</Ctx.Provider>;
}

export function useT(): I18nCtx {
  const c = useContext(Ctx);
  if (!c) throw new Error("useT must be used within I18nProvider");
  return c;
}
